/**
 * 官方模板集（B3d 模板中心「推荐（官方）」tab 的前端内置 Markdown 集）。
 *
 * 消费方：components/knowledge/TemplateSelectDialog.vue——按 category 分组展示、
 * 选中后实时预览，「使用此模板」即以 text/markdown scheme 新建文档。
 * 官方模板为前端内置数据（无 updatedAt 语义，不参与 create-from-template 接口）。
 * 分类对齐语雀模板中心分类树实测（需求梳理 5.3：团队协作 11 类全量 + 个人管理组），
 * 2026-09-22 复原：13 个模板与分类树子项一一对应（对话框分类树数量小字依赖此对应）。
 */

/** 描述一个官方内置模板条目。 */
export interface OfficialTemplate {
  /** 唯一标识（对话框用作模板 key） */
  id: string
  /** 模板名（同时作为新文档标题） */
  title: string
  /** 分类名（模板列表按它分组展示，也是对话框分类树的子项） */
  category: string
  /** 一句话用途说明（列表项次行） */
  description: string
  /** Markdown 正文 */
  content: string
}

